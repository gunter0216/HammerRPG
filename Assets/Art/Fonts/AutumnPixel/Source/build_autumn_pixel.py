GLYPHS = {}


def glyph(char, pattern, bottom=0, advance=None):
    rows = pattern.split('/') if pattern else []
    GLYPHS[char] = {'rows': rows, 'bottom': bottom, 'advance': advance}


def alias(characters, original):
    for char in characters:
        GLYPHS[char] = dict(GLYPHS[original])


