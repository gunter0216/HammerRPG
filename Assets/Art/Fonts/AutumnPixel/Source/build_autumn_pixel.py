def main():
    try:
        from fontTools.fontBuilder import FontBuilder
        from fontTools.pens.ttGlyphPen import TTGlyphPen
        from fontTools.ttLib import TTFont
    except ImportError:
        print('FontTools is required. Install it in your build environment.')
        return False
    for char, data in GLYPHS.items():
        rows = data['rows']
        if rows and (any(len(row) != len(rows[0]) for row in rows) or any(set(row) - {'.', '#'} for row in rows)):
            print(f'Invalid bitmap for {char!r}: {rows}')
            return False
    required = ''.join(chr(i) for i in range(32,127)) + ''.join(chr(i) for i in range(0x410,0x450)) + 'Ёё'
    missing = set(required) - GLYPHS.keys()
    if missing:
        print(f'Missing glyphs: {missing}')
        return False
    unit = 64
    order = ['.notdef'] + [f'uni{ord(char):04X}' for char in sorted(GLYPHS)]
    cmaps = {ord(char): f'uni{ord(char):04X}' for char in sorted(GLYPHS)}
    outlines = {}
    metrics = {}
    all_data = {'.notdef': {'rows':['#######','#.....#','#.#.#.#','#..#..#','#.#.#.#','#.....#','#######'], 'bottom':0,'advance':8}}
    all_data.update({f'uni{ord(char):04X}': data for char,data in GLYPHS.items()})
    for name, data in all_data.items():
        rows = data['rows']
        width = len(rows[0]) if rows else 0
        pen = TTGlyphPen(None)
        # A two-pixel pen gives the compact body face the weight of the game's
        # reference. Merge adjacent pixels into runs before emitting outlines.
        pixels = set()
        for row_index, row in enumerate(rows):
            for column, pixel in enumerate(row):
                if pixel == '#':
                    y = len(rows)-1-row_index+data['bottom']
                    pixels.update((column+1+dx, y+dy) for dx in (0,1) for dy in (0,1))
        for y in sorted({y for _,y in pixels}):
            columns = sorted(x for x, py in pixels if py == y)
            index = 0
            while index < len(columns):
                start = columns[index]
                end = start+1
                index += 1
                while index < len(columns) and columns[index] == end:
                    end += 1
                    index += 1
                left, right = start*unit, end*unit
                bottom = y*unit
                pen.moveTo((left,bottom))
                pen.lineTo((left,bottom+unit))
                pen.lineTo((right,bottom+unit))
                pen.lineTo((right,bottom))
                pen.closePath()
        outlines[name] = pen.glyph()
        advance = data['advance'] if data['advance'] is not None else width+2
        metrics[name] = (advance*unit, unit if rows else 0)
    font = FontBuilder(1024, isTTF=True)
    font.setupGlyphOrder(order)
    font.setupCharacterMap(cmaps)
    font.setupGlyf(outlines)
    font.setupHorizontalMetrics(metrics)
    font.setupHorizontalHeader(ascent=13*unit, descent=-3*unit, lineGap=0)
    font.setupNameTable({'familyName':'Autumn Pixel','styleName':'Regular','uniqueFontIdentifier':'AutumnPixel-Regular-1.000','fullName':'Autumn Pixel Regular','psName':'AutumnPixel-Regular','version':'Version 1.000','copyright':'Original pixel glyph geometry created for the Autumn game project.'})
    font.setupOS2(sTypoAscender=13*unit,sTypoDescender=-3*unit,sTypoLineGap=0,usWinAscent=13*unit,usWinDescent=3*unit,sxHeight=8*unit,sCapHeight=10*unit,usWeightClass=600,fsSelection=0x40)
    font.setupPost()
    font.setupMaxp()
    destination = ROOT / 'Assets/Art/Fonts/AutumnPixel'
    destination.mkdir(parents=True, exist_ok=True)
    output = destination / 'AutumnPixel-Regular.ttf'
    font.save(output)
    # Re-open the deliverable through a second reader before importing into Unity.
    loaded = TTFont(output)
    if not set(cmaps).issubset(loaded.getBestCmap()):
        print('TTF verification failed.')
        return False
    (destination/'Characters.txt').write_text(''.join(sorted(GLYPHS)),encoding='utf-8')
    print(json.dumps({'success':True,'characters':len(cmaps),'glyphs':len(order),'path':str(output),'bytes':output.stat().st_size},ensure_ascii=False))
    return True


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
